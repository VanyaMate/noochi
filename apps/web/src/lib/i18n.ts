export type LangKey = keyof typeof LANGS;

interface I18nState {
  lang: LangKey;
  setLang: (l: LangKey) => void;
}

export const useI18n = create<I18nState>((set) => ({
  lang: ((localStorage.getItem('noochi.lang') as LangKey) ?? 'ru'),
  setLang: (lang) => { localStorage.setItem('noochi.lang', lang); set({ lang }); },
}));

export function useT() {
  const lang = useI18n((s) => s.lang);
  return (key: keyof typeof LANGS.ru) => LANGS[lang][key] ?? LANGS.ru[key] ?? String(key);
}
